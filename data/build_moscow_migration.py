"""Generate migration 004 from the coordinate-bearing catalog entries (no network)."""
import datetime as dt
import json
import re
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAMESPACE = uuid.UUID('ee8c401e-4fa8-40ba-a6ac-784cf1115dac')

def literal(value):
    return "'" + str(value).replace("'", "''") + "'"

def build():
    catalog = json.loads((ROOT / 'data/moscow-events.json').read_text(encoding='utf-8'))
    events = [e for e in catalog['events'] if e.get('latitude') is not None and e.get('longitude') is not None]
    assert len(events) == 58
    rows = []
    ids = set()
    for e in events:
        source_date = e['reported_date']
        if e.get('date'):
            start = end = dt.date.fromisoformat(e['date'])
        else:
            m = re.match(r'^(\d{1,2})(?:–(\d{1,2}))?\.(\d{2})(?:,|$)', source_date)
            if not m:
                raise ValueError((e['key'], source_date))
            day, last, month = m.groups()
            month = int(month)
            year = 2027 if month == 1 else 2026
            start = dt.date(year, month, int(day))
            end = dt.date(year, month, int(last or day))
        match = re.search(r'\b\d{1,2}:\d{2}\b', source_date)
        start_time = dt.time.fromisoformat(match.group()) if match else None
        assert start <= end
        assert dt.date(2026, 11, 23) <= start <= end <= dt.date(2027, 1, 15)
        assert e['title'].strip() and e['reported_location'].strip()
        assert -90 <= e['latitude'] <= 90 and -180 <= e['longitude'] <= 180
        event_id = str(uuid.uuid5(NAMESPACE, e['key']))
        assert event_id not in ids
        ids.add(event_id)
        location = e['reported_location']
        if location == 'Там же. 2 000 ₽':
            location = 'Карманицкий пер., 3Ас4'
        # Remove prices and admission conditions from the map's location label.
        location = re.sub(r'\. Бесплатно(?=\.|$)', '', location)
        location = re.sub(r'\. 2 000 ₽$', '', location).strip()
        details = ['Данные для тестирования Locator.', 'Исходная локация: ' + e['reported_location']]
        if e.get('reported_details'):
            details.extend(e['reported_details'])
        if e.get('series_key'):
            details.append('Дата рассчитана по расписанию: ' + source_date + '.')
        sources = list(dict.fromkeys(e.get('sources', [])))
        if sources:
            details.append('Ссылки из исходной подборки (могут быть общими для нескольких событий):\n' + '\n'.join(sources))
        details.append('Координаты: ' + ('предоставлены пользователем.' if e.get('geocoding', {}).get('coordinate_source') == 'user' else 'OpenStreetMap Nominatim; © OpenStreetMap contributors, ODbL. https://www.openstreetmap.org/copyright'))
        values = [literal(event_id) + '::uuid', literal(e['title']), literal('\n\n'.join(details)),
                  'date ' + literal(start), 'date ' + literal(end),
                  'time ' + literal(start_time) if start_time else 'NULL', 'NULL',
                  literal('Europe/Moscow'), literal(location), str(e['latitude']), str(e['longitude'])]
        rows.append('  -- ' + e['key'] + '\n  (' + ', '.join(values) + ')')
    header = '''-- Test events from data/moscow-events.json: 58 records with coordinates.
-- Requires 003_split_event_dates.sql, or the equivalent current schema.sql.
-- Fixed calendar dates; unknown times remain NULL. No schema changes.
-- Stable UUIDv5 IDs derived from catalog keys; reruns preserve existing rows.
-- Generated by data/build_moscow_migration.py; source snapshot remains in data/.
begin;

insert into public.events (
  id, title, description, start_date, end_date, start_time, end_time,
  timezone, location_name, latitude, longitude
) values
'''
    return header + ',\n'.join(rows) + '\non conflict (id) do nothing;\n\ncommit;\n'

if __name__ == '__main__':
    sql = build()
    path = ROOT / 'supabase/migrations/004_seed_moscow_events.sql'
    path.write_text(sql, encoding='utf-8')
    print('Generated 58 records:', path)
